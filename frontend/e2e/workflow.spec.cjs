const {test,expect} = require('@playwright/test')
test('customer evidence workflow through the real UI',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await page.getByRole('button',{name:'Create account',exact:true}).click()
 await page.getByLabel('Email',{exact:true}).fill(`browser-${Date.now()}@example.com`)
 await page.getByLabel('Password',{exact:true}).fill('BrowserTestPassword42!')
 await page.getByRole('button',{name:'Create account',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Executive Overview'})).toBeVisible()
 await page.getByRole('button',{name:'Import data',exact:true}).click()
 await page.getByRole('button',{name:'Create synthetic demo dataset'}).click()
 await expect(page.locator('.toast')).toContainText('Synthetic dataset created',{timeout:60000})
 await page.goto('/model-performance')
 await page.getByLabel('Training dataset').selectOption({index:1})
 await page.getByRole('button',{name:'Train & compare models'}).click()
 await expect(page.locator('.toast')).toContainText('Model candidates evaluated',{timeout:120000})
 await expect(page.getByRole('heading',{name:'Validation comparison'})).toBeVisible({timeout:120000})
 await page.getByRole('button',{name:'Run batch prediction'}).click()
 await expect(page.locator('.toast')).toContainText('Batch predictions stored',{timeout:60000})
 await page.goto('/customer-directory')
 await page.getByLabel('Risk filter').selectOption('High')
 await expect(page.locator('tbody tr').first()).toBeVisible()
 await page.getByRole('button',{name:/Open DEMO/}).first().click()
 await expect(page.getByRole('heading',{name:'Customer Profile'})).toBeVisible()
 await page.getByRole('button',{name:'Predict customer churn'}).click()
 await expect(page.locator('.prediction-score')).toBeVisible({timeout:30000})
 await page.goto('/orchestrator-agent')
 await page.getByRole('button',{name:'Run customer workflow'}).click()
 await expect(page.locator('.toast')).toContainText('paused for human review',{timeout:60000})
 await page.goto('/retail-ai-assistant')
 await page.getByRole('button',{name:'Ask assistant',exact:true}).click()
 await expect(page.locator('.assistant-answer')).toContainText('Retrieved')
 await page.goto('/retention-reports')
 await page.getByRole('button',{name:'Generate report'}).click()
 await expect(page.locator('tbody tr').first()).toBeVisible()
 const downloadPromise=page.waitForEvent('download')
 await page.getByRole('button',{name:'JSON',exact:true}).first().click()
 expect((await downloadPromise).suggestedFilename()).toMatch(/retainiq-report-.*\.json/)
 await page.goto('/executive-overview');await expect(page.locator('.kpi > strong').first()).toBeVisible()
 expect(Number((await page.locator('.kpi > strong').first().innerText()).replaceAll(',',''))).toBeGreaterThan(0)
 await expect(page.locator('.recharts-bar-rectangle path').first()).toBeVisible()
 await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 expect(errors).toEqual([])
})
