// Credentials arrive through a pipe from the hidden Python prompt; never CLI arguments.
const {chromium,expect}=require('@playwright/test')
const path=require('node:path')
const fs=require('node:fs')
async function main(){
 let input='';for await(const chunk of process.stdin)input+=chunk
 const credentials=JSON.parse(input)
 const base=process.argv[2]
 const browser=await chromium.launch({channel:'chrome',headless:true})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(base)
  await page.getByLabel('Email',{exact:true}).fill(credentials.email)
  await page.getByLabel('Password',{exact:true}).fill(credentials.password)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Executive Overview'})).toBeVisible({timeout:30000})
  await expect(page.locator('.kpi > strong').first()).toHaveText('360',{timeout:30000})
  await expect(page.getByText('Hosted environment',{exact:true})).toBeVisible()
  console.log('Hosted login and persisted customer analytics: passed')
  await page.goto(base+'/high-risk-customers')
  await expect(page.locator('tbody tr').first()).toBeVisible({timeout:30000})
  await page.getByRole('button',{name:/Open DEMO/}).first().click()
  await page.getByRole('button',{name:'Predict customer churn'}).click()
  await expect(page.locator('.prediction-score')).toBeVisible({timeout:30000})
  console.log('Persisted model artifact prediction: passed')
  await page.goto(base+'/ai-agent-dashboard')
  await expect(page.getByText('awaiting_review',{exact:true}).first()).toBeVisible({timeout:30000})
  console.log('Persisted agent execution: passed')
  await page.goto(base+'/retail-ai-assistant')
  await page.getByRole('button',{name:'Why is this customer at risk?',exact:true}).click()
  await page.getByRole('button',{name:'Ask assistant',exact:true}).click()
  await expect(page.locator('.assistant-answer')).toContainText('Retrieved',{timeout:30000})
  console.log('Hosted tool-grounded assistant: passed')
  await page.goto(base+'/executive-overview')
  await expect(page.locator('.kpi > strong').first()).toHaveText('360',{timeout:30000})
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('.recharts-bar-rectangle path')).some(e=>e.getBoundingClientRect().width>30),{timeout:15000})
  const output=path.resolve(__dirname,'../test-results')
  fs.mkdirSync(output,{recursive:true})
  await page.screenshot({path:path.join(output,'hosted-dashboard-desktop.png'),fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await expect(page.getByRole('heading',{name:'Executive Overview'})).toBeVisible()
  await page.screenshot({path:path.join(output,'hosted-dashboard-mobile.png'),fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
  console.log('Hosted desktop/mobile UI and JavaScript checks: passed')
 }finally{await browser.close()}
}
main().catch(()=>{console.error('Hosted browser verification failed. Inspect the step preceding this message.');process.exitCode=1})
