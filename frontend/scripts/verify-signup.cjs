const {chromium,expect}=require('@playwright/test')
const crypto=require('node:crypto')
const fs=require('node:fs')
const path=require('node:path')
async function main(){
 const browser=await chromium.launch({channel:'chrome',headless:true})
 const base='https://retainiq-ai.vercel.app'
 try{
  const page=await browser.newPage({viewport:{width:1366,height:900}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(base)
  await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Create account',exact:true})).toBeVisible()
  const output=path.resolve(__dirname,'../test-results');fs.mkdirSync(output,{recursive:true})
  await page.screenshot({path:path.join(output,'create-account-option.png'),fullPage:true})
  await page.getByRole('button',{name:'Create account',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Create your workspace account'})).toBeVisible()
  await page.screenshot({path:path.join(output,'create-account-form.png'),fullPage:true})
  const email=`signup-check-${Date.now()}@example.com`
  const password=crypto.randomBytes(24).toString('base64url')
  await page.getByLabel('Email',{exact:true}).fill(email)
  await page.getByLabel('Password',{exact:true}).fill(password)
  const registered=page.waitForResponse(r=>r.url().endsWith('/api/auth/register')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'Create account',exact:true}).click()
  const response=await registered;expect(response.status()).toBe(201)
  expect((await response.json()).user.role).toBe('analyst')
  await expect(page.getByRole('heading',{name:'Executive Overview'})).toBeVisible({timeout:30000})
  console.log('Create account and automatic analyst sign-in: passed')
  await page.goto(base+'/user-management')
  await expect(page.getByText('This action requires an authorized role',{exact:true})).toBeVisible({timeout:30000})
  console.log('Administrator access remains restricted: passed')
  await page.getByRole('button',{name:'Sign out analyst',exact:true}).click()
  await page.goto(base)
  await page.getByLabel('Email',{exact:true}).fill(email)
  await page.getByLabel('Password',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Executive Overview'})).toBeVisible({timeout:30000})
  expect(errors).toEqual([])
  console.log('Subsequent sign-in and browser checks: passed')
 }finally{await browser.close()}
}
main().catch(e=>{console.error(e.message);process.exitCode=1})
